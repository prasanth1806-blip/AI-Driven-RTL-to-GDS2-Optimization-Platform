#!/usr/bin/env python3
"""Generate a testbench that matches a design's actual port list.

The generators this replaces emitted a fixed harness wired to
clk/rst/data_in/data_out. That worked for exactly one module -- the built-in
template -- and silently produced an uncompilable testbench for anything a
user uploaded. Here the port list is read out of the RTL (scripts/rtl_parse)
and the harness is built from it: real widths, real directions, real reset
polarity.

What the generated testbench can and cannot do is worth being explicit
about. It cannot check functional correctness, because nothing here knows
what the design is supposed to compute. What it does is exercise the design
so the rest of the flow has something to work with: hold reset, release it,
drive pseudo-random stimulus on every data input for a fixed number of
cycles, dump a VCD, and report what it observed on the outputs (including
how often they sat at X, which is usually the first sign of an
uninitialised path). It always terminates, which the previous generator's
output did not reliably do.

Usage:
  gen_tb.py <rtl.sv> <out_file> [--lang sv|python] [--top NAME]
                                [--cycles N] [--period NS]
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from rtl_parse import (  # noqa: E402
    data_inputs, find_clock, find_reset, parse_sources, ports_by_direction,
)

DEFAULT_CYCLES = 32
DEFAULT_PERIOD_NS = 10
RESET_CYCLES = 3


# ---------------------------------------------------------------------------
# Shared helpers
# ---------------------------------------------------------------------------

def needs_params(module):
    """True when some port width could not be resolved to a constant.

    In that case the testbench declares the design's parameters as localparams
    and reuses the port's own range expression verbatim, rather than guessing a
    width. Guessing here would produce a testbench that compiles and drives the
    wrong number of bits, which is far worse than one that fails to compile.
    """
    return any(port["width"] is None for port in module["ports"])


def sv_range(port):
    """SystemVerilog packed range for a port declaration, or ''."""
    if port["width"] is not None:
        return "" if port["width"] <= 1 else f"[{port['width'] - 1}:0] "
    return f"[{port['msb']}:{port['lsb']}] "


def random_expr(port):
    """An expression yielding a fresh pseudo-random value of the port's width.

    $random is 32 bits wide, so anything wider is built by concatenation --
    assigning a bare $random to a 64-bit port would leave the upper half
    stuck at zero for the whole run and hide half the logic from the VCD.
    """
    width = port["width"]
    if width is None or width <= 32:
        return "$random(seed)"
    chunks = -(-width // 32)  # ceil
    return "{" + ", ".join(["$random(seed)"] * chunks) + "}"


# ---------------------------------------------------------------------------
# SystemVerilog testbench
# ---------------------------------------------------------------------------

def build_sv(module, cycles, period):
    name = module["name"]
    tb_name = f"test_{name}"
    clock = find_clock(module)
    reset = find_reset(module)
    inputs = ports_by_direction(module, "input")
    outputs = ports_by_direction(module, "output")
    inouts = ports_by_direction(module, "inout")
    stim_ports = data_inputs(module)

    out = [
        "`timescale 1ns/1ps",
        "//",
        f"// Auto-generated by scripts/gen_tb.py for module `{name}`.",
        "//",
        "// Exercises the design and dumps a VCD. It does not check functional",
        "// correctness -- the intended behaviour of the design is not known",
        "// here -- so it reports observed output activity instead of asserting",
        "// expected values. Replace the stimulus block to make it self-checking.",
        "//",
        f"module {tb_name};",
        "",
    ]

    if needs_params(module):
        out.append("    // Copied from the design: some port widths depend on these.")
        for param, value in module["params"].items():
            out.append(f"    localparam {param} = {value};")
        out.append("")

    out += [
        f"    localparam integer CLK_PERIOD  = {period};",
        f"    localparam integer STIM_CYCLES = {cycles};",
        f"    localparam integer RESET_CYCLES = {RESET_CYCLES};",
        "",
        "    integer seed = 32'h1234_5678;",
        "    integer i;",
        "    integer x_samples = 0;",
        "    integer samples   = 0;",
        "",
        "    // Design inputs are driven, outputs observed, inouts left floating",
        "    // (an auto-generated harness has no way to know when it may drive a",
        "    // bidirectional pin without contending with the design).",
    ]

    for port in inputs:
        out.append(f"    reg  {sv_range(port)}{port['name']};")
    for port in outputs:
        out.append(f"    wire {sv_range(port)}{port['name']};")
    for port in inouts:
        out.append(f"    wire {sv_range(port)}{port['name']};")
    out.append("")

    # Instantiate with named connections so port order never matters.
    connections = [f".{p['name']}({p['name']})"
                   for p in module["ports"]]
    out.append(f"    {name} dut (")
    out += [f"        {c}," for c in connections[:-1]]
    if connections:
        out.append(f"        {connections[-1]}")
    out.append("    );")
    out.append("")

    if clock:
        out += [
            "    initial " + clock["name"] + " = 1'b0;",
            f"    always #(CLK_PERIOD/2) {clock['name']} = ~{clock['name']};",
            "",
        ]

    # ---- stimulus ----
    out += [
        "    initial begin",
        f'        $dumpfile("{name}.vcd");',
        f"        $dumpvars(0, {tb_name});",
        "",
    ]

    if reset:
        asserted = "1'b0" if reset["active_low"] else "1'b1"
        released = "1'b1" if reset["active_low"] else "1'b0"
        polarity = "active low" if reset["active_low"] else "active high"
        out.append(f"        // Hold {reset['name']} ({polarity}) through startup.")
        out.append(f"        {reset['name']} = {asserted};")

    for port in stim_ports:
        out.append(f"        {port['name']} = {{{port['width'] or 1}{{1'b0}}}};"
                   if port["width"] and port["width"] > 1
                   else f"        {port['name']} = 1'b0;")
    out.append("")

    if clock:
        out.append(f"        repeat (RESET_CYCLES) @(posedge {clock['name']});")
    else:
        out.append("        #(CLK_PERIOD * RESET_CYCLES);")

    if reset:
        out.append(f"        {reset['name']} = {released};")
        if clock:
            out.append(f"        @(posedge {clock['name']});")
        else:
            out.append("        #(CLK_PERIOD);")
    out.append("")

    if stim_ports:
        out.append("        for (i = 0; i < STIM_CYCLES; i = i + 1) begin")
        for port in stim_ports:
            out.append(f"            {port['name']} <= {random_expr(port)};")
        if clock:
            out.append(f"            @(posedge {clock['name']});")
        else:
            out.append("            #(CLK_PERIOD);")
        out.append("        end")
    else:
        out.append("        // No data inputs to drive; just let the design run.")
        if clock:
            out.append(f"        repeat (STIM_CYCLES) @(posedge {clock['name']});")
        else:
            out.append("        #(CLK_PERIOD * STIM_CYCLES);")
    out.append("")

    out += [
        "        // Drain a few more cycles so the last stimulus reaches the outputs.",
    ]
    if clock:
        out.append(f"        repeat (4) @(posedge {clock['name']});")
    else:
        out.append("        #(CLK_PERIOD * 4);")

    out += [
        "",
        f'        $display("[{tb_name}] ran %0d stimulus cycles", STIM_CYCLES);',
    ]
    if outputs:
        out.append(
            f'        $display("[{tb_name}] output samples=%0d, '
            f'samples containing x/z=%0d", samples, x_samples);'
        )
    out.append("        $finish;")
    out.append("    end")
    out.append("")

    # ---- output observation ----
    if outputs:
        out.append("    // Count how often the outputs are undefined. This is reported,")
        out.append("    // not asserted on: a design with uninitialised memory legitimately")
        out.append("    // reads X early on, so failing the run here would be wrong.")
        trigger = (f"@(posedge {clock['name']})" if clock
                   else f"@({' or '.join(p['name'] for p in outputs)})")
        out.append(f"    always {trigger} begin")
        out.append("        samples = samples + 1;")
        reductions = " || ".join(f"(^{p['name']} === 1'bx)" for p in outputs)
        out.append(f"        if ({reductions}) x_samples = x_samples + 1;")
        out.append("    end")
        out.append("")

    out += [
        "    // Hard stop, so a design that never settles cannot hang the flow.",
        "    initial begin",
        "        #(CLK_PERIOD * (STIM_CYCLES + RESET_CYCLES + 64) * 4);",
        f'        $display("[{tb_name}] timeout guard fired");',
        "        $finish;",
        "    end",
        "",
        "endmodule",
        "",
    ]
    return "\n".join(out)


