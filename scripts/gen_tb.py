def build_cocotb(module, cycles, period):
    name = module["name"]
    clock = find_clock(module)
    reset = find_reset(module)
    outputs = ports_by_direction(module, "output")
    stim_ports = data_inputs(module)

    lines = [
        '"""Auto-generated by scripts/gen_tb.py for module `%s`.' % name,
        "",
        "Exercises the design so the flow has stimulus and a waveform to work",
        "with. It deliberately does not assert expected output values -- the",
        "intended behaviour of the design is not known here. Add real checks",
        "in place of the observation loop to make this a functional test.",
        '"""',
        "import random",
        "",
        "import cocotb",
        "from cocotb.clock import Clock",
        "from cocotb.triggers import RisingEdge, Timer",
        "",
        f"CLK_PERIOD_NS = {period}",
        f"STIM_CYCLES = {cycles}",
        f"RESET_CYCLES = {RESET_CYCLES}",
        "",
        "# Fixed seed: a failing run has to be reproducible.",
        "SEED = 0x12345678",
        "",
    ]

    # Port width table drives random stimulus ranges.
    if stim_ports:
        lines.append("# Port name -> width in bits, taken from the RTL declaration.")
        lines.append("STIMULUS_PORTS = {")
        for port in stim_ports:
            width = port["width"] if port["width"] else 1
            comment = "" if port["width"] else "  # width unresolved; driven as 1 bit"
            lines.append(f'    "{port["name"]}": {width},{comment}')
        lines.append("}")
        lines.append("")

    # ---- helpers ----
    if clock:
        lines += [
            "async def _start_clock(dut):",
            f'    cocotb.start_soon(Clock(dut.{clock["name"]}, CLK_PERIOD_NS, unit="ns").start())',
            "",
            "",
        ]

    lines += ["async def _reset(dut):"]
    if reset:
        asserted = 0 if reset["active_low"] else 1
        released = 1 if reset["active_low"] else 0
        polarity = "active low" if reset["active_low"] else "active high"
        lines.append(f'    """Hold {reset["name"]} ({polarity}), then release it."""')
        lines.append(f"    dut.{reset['name']}.value = {asserted}")
    else:
        lines.append('    """No reset port on this design; just idle the inputs."""')
    for port in stim_ports:
        lines.append(f"    dut.{port['name']}.value = 0")
    if clock:
        lines.append("    for _ in range(RESET_CYCLES):")
        lines.append(f"        await RisingEdge(dut.{clock['name']})")
    else:
        lines.append("    await Timer(CLK_PERIOD_NS * RESET_CYCLES, unit=\"ns\")")
    if reset:
        lines.append(f"    dut.{reset['name']}.value = {released}")
    if clock:
        lines.append(f"    await RisingEdge(dut.{clock['name']})")
    else:
        lines.append('    await Timer(CLK_PERIOD_NS, unit="ns")')
    lines += ["", ""]

    # ---- reset test ----
    lines += [
        "@cocotb.test()",
        f"async def test_{name}_reset(dut):",
        '    """The design comes out of reset without the simulation dying."""',
    ]
    if clock:
        lines.append("    await _start_clock(dut)")
    lines.append("    await _reset(dut)")
    if outputs:
        lines.append('    dut._log.info("out of reset: " + _sample(dut))')
    else:
        lines.append('    dut._log.info("out of reset")')
    lines += ["", ""]

    # ---- stimulus test ----
    lines += [
        "@cocotb.test()",
        f"async def test_{name}_stimulus(dut):",
        '    """Drive pseudo-random stimulus and report the observed outputs."""',
        "    random.seed(SEED)",
    ]
    if clock:
        lines.append("    await _start_clock(dut)")
    lines.append("    await _reset(dut)")
    lines.append("")
    lines.append("    undefined = 0")
    lines.append("    for _ in range(STIM_CYCLES):")
    if stim_ports:
        lines.append("        for port, width in STIMULUS_PORTS.items():")
        lines.append("            getattr(dut, port).value = random.getrandbits(width)")
    else:
        lines.append("        pass  # no data inputs on this design")
    if clock:
        lines.append(f"        await RisingEdge(dut.{clock['name']})")
    else:
        lines.append('        await Timer(CLK_PERIOD_NS, unit="ns")')
    lines.append('        await Timer(1, unit="ns")  # settle past the edge')
    if outputs:
        lines.append("        if not _is_resolvable(dut):")
        lines.append("            undefined += 1")
    lines.append("")
    lines.append('    dut._log.info(f"ran {STIM_CYCLES} stimulus cycles")')
    if outputs:
        lines.append('    dut._log.info(f"cycles with an undefined output: {undefined}")')
        lines.append("    # Reported, not asserted: uninitialised memory reads X")
        lines.append("    # legitimately, so this must not fail an otherwise good run.")
    lines += ["", ""]

    # ---- observation helpers ----
    if outputs:
        names = ", ".join(f'"{p["name"]}"' for p in outputs)
        lines += [
            f"OUTPUT_PORTS = ({names},)" if len(outputs) == 1
            else f"OUTPUT_PORTS = ({names})",
            "",
            "",
            "def _sample(dut):",
            '    """Render every output as a string, X/Z included."""',
            "    return \", \".join(",
            '        f"{port}={getattr(dut, port).value}" for port in OUTPUT_PORTS',
            "    )",
            "",
            "",
            "def _is_resolvable(dut):",
            '    """True when every output holds a definite 0/1 value."""',
            "    for port in OUTPUT_PORTS:",
            "        try:",
            "            int(getattr(dut, port).value)",
            "        except ValueError:",
            "            return False",
            "    return True",
            "",
        ]

    return "\n".join(lines)


# ---------------------------------------------------------------------------

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("rtl", nargs="+", help="RTL source file(s)")
    parser.add_argument("out", help="testbench file to write")
    parser.add_argument("--lang", choices=("sv", "python"), default="sv")
    parser.add_argument("--top", default=None, help="top module name")
    parser.add_argument("--cycles", type=int, default=DEFAULT_CYCLES)
    parser.add_argument("--period", type=int, default=DEFAULT_PERIOD_NS)
    args = parser.parse_args()

    parsed = parse_sources(args.rtl, top=args.top)
    module = parsed["top_module"]
    if module is None:
        sys.exit(f"No module found in {', '.join(args.rtl)}")
    if args.top and parsed["top_found"] is False:
        sys.exit(f"Module '{args.top}' not found in {', '.join(args.rtl)}; "
                 f"available: {', '.join(m['name'] for m in parsed['modules'])}")
    if not module["ports"]:
        sys.exit(f"Module '{module['name']}' declares no ports; nothing to drive.")

    builder = build_cocotb if args.lang == "python" else build_sv
    text = builder(module, args.cycles, args.period)

    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    with open(args.out, "w") as handle:
        handle.write(text)

    ports = module["ports"]
    print(f"Wrote {args.out}: {args.lang} testbench for '{module['name']}' "
          f"({len(ports)} ports, "
          f"{sum(1 for p in ports if p['direction'] == 'input')} in / "
          f"{sum(1 for p in ports if p['direction'] == 'output')} out)")


if __name__ == "__main__":
    main()
